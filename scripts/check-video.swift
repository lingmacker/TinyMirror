import Foundation
import AVFoundation

@main
struct VideoChecks {
    static func main() {
        // H.264 SPS/PPS for a 1280×720 stream; no decoded picture is needed.
        let sps: [UInt8] = [0x67, 0x64, 0x00, 0x1f, 0xac, 0xd9, 0x40, 0x50,
                           0x05, 0xbb, 0x01, 0x10, 0x00, 0x00, 0x03, 0x00,
                           0x10, 0x00, 0x00, 0x03, 0x03, 0xc0, 0xf1, 0x83, 0x19, 0x60]
        let pps: [UInt8] = [0x68, 0xeb, 0xec, 0xb2, 0x2c]
        let frame = [0, 0, 0, 1] + sps + [0, 0, 0, 1] + pps
        let pipeline = VideoPipeline()
        var reports = 0
        pipeline.onDimensions = { width, height, isH265 in
            assert(!isH265)
            assert(width == 1280 && height == 720)
            reports += 1
        }

        for expected in 1...2 {
            if expected == 2 { pipeline.reset() }
            frame.withUnsafeBufferPointer { pipeline.handleAccessUnit($0.baseAddress!, $0.count) }
            let deadline = Date().addingTimeInterval(2)
            while reports < expected && Date() < deadline {
                RunLoop.current.run(until: Date().addingTimeInterval(0.01))
            }
            assert(reports == expected, "A same-resolution reconnect must report dimensions to reopen the window")
        }
        // HEVC parameter sets generated by VideoToolbox for a synthetic 1280×720 frame.
        let vps: [UInt8] = [64, 1, 12, 1, 255, 255, 1, 96, 0, 0, 3, 0, 176, 0, 0, 3, 0, 0, 3, 0, 93, 21, 192, 144]
        let hevcSPS: [UInt8] = [66, 1, 1, 1, 96, 0, 0, 3, 0, 176, 0, 0, 3, 0, 0, 3, 0, 93, 160, 2, 128, 128, 45, 22, 32, 87, 185, 22, 84, 64]
        let hevcPPS: [UInt8] = [68, 1, 192, 44, 188, 20, 201]
        let hevc = [0, 0, 0, 1] + vps + [0, 0, 0, 1] + hevcSPS + [0, 0, 0, 1] + hevcPPS
        pipeline.onDimensions = { width, height, isH265 in
            assert(width == 1280 && height == 720 && isH265)
            reports += 1
        }
        for expected in 3...4 {
            if expected == 4 { pipeline.reset() }
            hevc.withUnsafeBufferPointer { pipeline.handleAccessUnit($0.baseAddress!, $0.count, isH265: true) }
            let deadline = Date().addingTimeInterval(2)
            while reports < expected && Date() < deadline {
                RunLoop.current.run(until: Date().addingTimeInterval(0.01))
            }
            assert(reports == expected, "HEVC must negotiate dimensions after codec changes and reconnects")
        }
        let stopped = VideoPipeline()
        var staleReports = 0
        stopped.onDimensions = { _, _, _ in staleReports += 1 }
        frame.withUnsafeBufferPointer { stopped.handleAccessUnit($0.baseAddress!, $0.count) }
        stopped.reset()
        RunLoop.current.run(until: Date().addingTimeInterval(0.15))
        assert(staleReports == 0, "Stopping must invalidate already-queued size callbacks")
        frame.withUnsafeBufferPointer { stopped.handleAccessUnit($0.baseAddress!, $0.count) }
        let reconnectDeadline = Date().addingTimeInterval(2)
        while staleReports < 1 && Date() < reconnectDeadline {
            RunLoop.current.run(until: Date().addingTimeInterval(0.01))
        }
        assert(staleReports == 1, "A new stream must still report its size after stopping")
        // Synthetic 64×64 keyframes generated with VideoToolbox, not phone recordings.
        for (isH265, base64) in [
            (false, "AAAAASdkAAusVlDDeBBhFAAAAAEo7jywAAAAAQYFLUdWStxcTEM/lO/FETzRQ6gBAAADAAEDAAADAAECAAHmAAsAAAMAAAMAAAMAlgwDkSsBgAAAAAEluCAfgC5KrBE2ZhdIAInDIblqRp9HCs8OgWpUK2McE/5C9FaHIAAaTU/N8ASwR52A"),
            (true, "AAAAAUABDAH//wFgAAADALAAAAMAAAMAHhXAkAAAAAFCAQEBYAAAAwCwAAADAAADAB6gFCBBwY+IFe5FlRAAAAABRAHALLwUyQAAAAFOAQUyR1ZK3FxMQz+U78URPNFDqAEAAAMAAQMAAAMAAQIAAIcACwAAAwAAAwAAAwCgDAORKwEN/////4AAAAABKAGvMibA6IXof4arqWAS6qNQqKCRe5oum9x4Hw==")
        ] {
            let layer = AVSampleBufferDisplayLayer()
            let playback = VideoPipeline()
            playback.displayLayer = layer
            let keyframe = Data(base64Encoded: base64)!
            func enqueue() {
                keyframe.withUnsafeBytes {
                    playback.handleAccessUnit($0.bindMemory(to: UInt8.self).baseAddress!, $0.count, isH265: isH265)
                }
            }
            func waitForDisplay(_ ready: Bool) {
                let deadline = Date().addingTimeInterval(3)
                while layer.isReadyForDisplay != ready && Date() < deadline {
                    RunLoop.current.run(until: Date().addingTimeInterval(0.01))
                }
                assert(layer.isReadyForDisplay == ready, "Native decoding or displayed-image reset failed")
                assert(layer.sampleBufferRenderer.status != .failed)
            }
            enqueue()
            waitForDisplay(true)
            playback.flush()
            playback.reset()
            waitForDisplay(false)
            enqueue()
            waitForDisplay(true)
            playback.reset()
            waitForDisplay(false)
        }
        print("H.264/HEVC decoding, flush, stop and reconnect checks passed")
    }
}
